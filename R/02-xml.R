## =====================================================================
## 02-xml.R -- parametric ReMASTER XML generator.
##
## Structure (which reactions exist) depends only on the region count and
## is built once. Only the rate NUMBERS depend on theta, so this function
## is cheap enough to call inside a simulation loop.
## =====================================================================

num <- function(x) trimws(formatC(x, format = "g", digits = 10))

#' Build a multi-region SIR ReMASTER XML.
#'
#' @param beta   named vector of per-S-per-I transmission rates
#' @param mig    migration matrix, row = origin, col = destination
#' @param pop    named vector of region population sizes
#' @param seed_region  region in which to place the index case
#' @return a single XML string
build_remaster_xml <- function(beta, mig, pop,
                               mu = MU, psi_case = PSI_CASE, psi_seq = PSI_SEQ,
                               seed_region = SEED_REGION,
                               max_time = WEEKS_TOTAL,
                               must_have = NULL) {

  regions <- names(pop)
  n <- length(regions)
  idx <- seq_len(n) - 1L                       # ReMASTER is 0-indexed

  ## initial conditions: one infection in the seed region
  I0 <- ifelse(regions == seed_region, 1, 0)
  S0 <- pop - I0

  r_trans <- paste0(
    sprintf('      <reaction spec="Reaction" rate="%s"> S[%d] + I[%d] -> 2I[%d] </reaction>',
            num(beta[regions]), idx, idx, idx),
    collapse = "\n")

  r_mig <- character(0)
  for (i in seq_len(n)) for (j in seq_len(n)) {
    if (i == j || mig[regions[i], regions[j]] <= 0) next
    r_mig <- c(r_mig, sprintf(
      '      <reaction spec="Reaction" rate="%s"> I[%d] -> I[%d] </reaction>   <!-- %s -> %s -->',
      num(mig[regions[i], regions[j]]), idx[i], idx[j], regions[i], regions[j]))
  }
  r_mig <- paste0(r_mig, collapse = "\n")

  samp_pops <- paste0(sprintf("seq[%d]", idx), collapse = ",")

  cond <- if (is.null(must_have)) "" else sprintf('\n                mustHave="%s"', must_have)

  glue::glue('<beast version="2.0"
       namespace="beast.base.inference:beast.base.inference.parameter:beast.base.evolution.tree:remaster">

<!-- GENERATED by R/02-xml.R : do not edit by hand.
     Regions: {paste(regions, collapse=", ")}   (0-indexed in reactions)
     Time unit: weeks. Seed region: {seed_region}. -->

<run spec="Simulator" nSims="1">
  <simulate id="tree" spec="SimulatedTree">
    <trajectory id="traj" spec="StochasticTrajectory" maxTime="{num(max_time)}"{cond}>

      <population       id="S"    spec="RealParameter" value="{paste(num(S0), collapse=" ")}"/>
      <population       id="I"    spec="RealParameter" value="{paste(num(I0), collapse=" ")}"/>
      <samplePopulation id="case" spec="RealParameter" value="{paste(rep(0,n), collapse=" ")}"/>
      <samplePopulation id="seq"  spec="RealParameter" value="{paste(rep(0,n), collapse=" ")}"/>

      <!-- transmission: rate_i = R0_i * delta / N_i -->
{r_trans}

      <!-- unobserved recovery -->
      <plate var="i" range="0:{n-1}">
        <reaction spec="Reaction" rate="{num(mu)}"> I[$(i)] -> 0 </reaction>
      </plate>

      <!-- detection with removal, split into sequenced / not sequenced -->
      <plate var="i" range="0:{n-1}">
        <reaction spec="Reaction" rate="{num(psi_case)}"> I[$(i)] -> case[$(i)] </reaction>
        <reaction spec="Reaction" rate="{num(psi_seq)}">  I[$(i)] -> seq[$(i)]  </reaction>
      </plate>

      <!-- migration -->
{r_mig}

    </trajectory>
  </simulate>

  <logger fileName="$(filebase).traj">
    <log idref="traj"/>
  </logger>

  <!-- tree pruned to SEQUENCED tips only; case-only tips are dropped -->
  <logger fileName="$(filebase).sampled.trees" mode="tree">
    <log spec="TypedTreeLogger">
      <tree spec="PrunedTree" samplePops="{samp_pops}" simulatedTree="@tree"/>
    </log>
  </logger>
</run>
</beast>
', .trim = FALSE)
}

#' Write XML, run BEAST2, return paths to the outputs.
run_remaster <- function(xml, stem, dir = SCRATCH, seed = SEED, quiet = TRUE) {
  xml_path <- file.path(dir, paste0(stem, ".xml"))
  writeLines(xml, xml_path)
  ## BEAST resolves $(filebase) against the PROCESS working directory, not the
  ## XML's location, so we must chdir or outputs land wherever R happens to be.
  old <- setwd(dir); on.exit(setwd(old), add = TRUE)
  out <- system2(BEAST, c("-seed", seed, "-overwrite", shQuote(paste0(stem, ".xml"))),
                 stdout = TRUE, stderr = TRUE)
  ok <- any(grepl("Done!", out, fixed = TRUE))
  if (!ok) { cat(tail(out, 30), sep = "\n"); stop("BEAST2 run failed") }
  if (!quiet) cat(tail(out, 3), sep = "\n")
  list(traj  = file.path(dir, paste0(stem, ".traj")),
       trees = file.path(dir, paste0(stem, ".sampled.trees")),
       xml   = xml_path)
}
